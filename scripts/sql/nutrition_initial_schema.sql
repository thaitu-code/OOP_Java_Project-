CREATE TABLE public.food_categories (
    category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name varchar(100) NOT NULL,
    category_name_key varchar(100) NOT NULL,
    description varchar(1000),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uk_food_category_name_key UNIQUE (category_name_key),
    CONSTRAINT ck_food_category_time CHECK (updated_at >= created_at)
);

CREATE TABLE public.foods (
    food_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id integer NOT NULL REFERENCES public.food_categories(category_id) ON DELETE RESTRICT,
    food_name varchar(150) NOT NULL,
    food_name_key varchar(150) NOT NULL,
    description varchar(2000),
    source varchar(500),
    image_url varchar(500),
    calories_per_100g numeric(7,2) NOT NULL,
    protein numeric(6,2) NOT NULL,
    carbs numeric(6,2) NOT NULL,
    fat numeric(6,2) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uk_food_name_key UNIQUE (food_name_key),
    CONSTRAINT ck_food_values CHECK (
        calories_per_100g >= 0 AND protein >= 0 AND carbs >= 0 AND fat >= 0 AND updated_at >= created_at
    )
);
CREATE INDEX ix_food_category_active ON public.foods(category_id, is_active);

CREATE TABLE public.daily_meal_logs (
    meal_log_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    log_date date NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT uk_nutrition_user_date UNIQUE (user_id, log_date)
);

CREATE TABLE public.meal_details (
    meal_detail_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_log_id integer NOT NULL REFERENCES public.daily_meal_logs(meal_log_id) ON DELETE RESTRICT,
    food_id integer NOT NULL REFERENCES public.foods(food_id) ON DELETE RESTRICT,
    meal_type varchar(16) NOT NULL,
    weight_grams numeric(7,2) NOT NULL,
    note varchar(500),
    food_name_snapshot varchar(150) NOT NULL,
    category_name_snapshot varchar(100) NOT NULL,
    image_url_snapshot varchar(500),
    calories_per_100g_snapshot numeric(7,2) NOT NULL,
    protein_per_100g_snapshot numeric(6,2) NOT NULL,
    carbs_per_100g_snapshot numeric(6,2) NOT NULL,
    fat_per_100g_snapshot numeric(6,2) NOT NULL,
    calculated_calories numeric(12,2) NOT NULL,
    calculated_protein numeric(12,2) NOT NULL,
    calculated_carbs numeric(12,2) NOT NULL,
    calculated_fat numeric(12,2) NOT NULL,
    logged_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    created_source varchar(16) NOT NULL,
    last_modified_source varchar(16) NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT ck_meal_type CHECK (meal_type IN ('BREAKFAST','LUNCH','AFTERNOON','DINNER')),
    CONSTRAINT ck_meal_created_source CHECK (created_source IN ('USER','AI')),
    CONSTRAINT ck_meal_modified_source CHECK (last_modified_source IN ('USER','AI')),
    CONSTRAINT ck_meal_detail_values CHECK (
        weight_grams > 0 AND calculated_calories >= 0 AND calculated_protein >= 0
        AND calculated_carbs >= 0 AND calculated_fat >= 0
        AND calories_per_100g_snapshot >= 0 AND protein_per_100g_snapshot >= 0
        AND carbs_per_100g_snapshot >= 0 AND fat_per_100g_snapshot >= 0 AND updated_at >= logged_at
    )
);
CREATE INDEX ix_meal_detail_log_meal ON public.meal_details(meal_log_id, meal_type);
COMMIT;
