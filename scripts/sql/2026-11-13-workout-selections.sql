-- Additive migration for environments using ddl-auto=validate/none.
-- Existing environments with ddl-auto=update create the equivalent JPA table on startup.
CREATE TABLE IF NOT EXISTS workout_selections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    request_id UUID NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    session_id INTEGER NOT NULL REFERENCES workout_sessions(session_id),
    CONSTRAINT uk_workout_selection_user_request UNIQUE (user_id, request_id)
);
