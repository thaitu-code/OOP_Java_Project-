-- Chạy thủ công trên đúng DB sau khi sao lưu. Không dùng Flyway.
-- Chỉ thêm cấu trúc; không gán cấp độ/thời gian giả cho dữ liệu tập cũ.
BEGIN;
ALTER TABLE public.exercises ADD COLUMN IF NOT EXISTS media_url varchar(500);
CREATE TABLE IF NOT EXISTS public.exercise_levels (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_id integer NOT NULL REFERENCES public.exercises(exercise_id) ON DELETE CASCADE,
    name varchar(100) NOT NULL,
    sets integer NOT NULL CHECK (sets BETWEEN 1 AND 100),
    reps integer CHECK (reps IS NULL OR reps > 0),
    seconds_per_set integer NOT NULL CHECK (seconds_per_set BETWEEN 1 AND 86400),
    rest_seconds integer NOT NULL CHECK (rest_seconds BETWEEN 1 AND 300),
    estimated_seconds integer NOT NULL CHECK (estimated_seconds BETWEEN 1 AND 86400),
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_exercise_levels_name UNIQUE (exercise_id, name)
);
ALTER TABLE public.workout_details
    ADD COLUMN IF NOT EXISTS level_id_snapshot integer,
    ADD COLUMN IF NOT EXISTS level_name_snapshot varchar(100),
    ADD COLUMN IF NOT EXISTS planned_sets_snapshot integer,
    ADD COLUMN IF NOT EXISTS planned_reps_snapshot integer,
    ADD COLUMN IF NOT EXISTS seconds_per_set_snapshot integer,
    ADD COLUMN IF NOT EXISTS estimated_seconds_snapshot integer,
    ADD COLUMN IF NOT EXISTS current_set_number integer,
    ADD COLUMN IF NOT EXISTS elapsed_in_set_millis bigint,
    ADD COLUMN IF NOT EXISTS automatic_rest_phase boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS media_url_snapshot varchar(500);
CREATE INDEX IF NOT EXISTS idx_workout_details_automatic_rest_heartbeat
    ON public.workout_details (last_heartbeat_at, session_id)
    WHERE status = 'RESTING' AND estimated_seconds_snapshot IS NOT NULL;
-- Hibernate có thể đã tạo bảng trước khi chạy file này; vẫn bổ sung CHECK còn thiếu.
DO $$
DECLARE definition text;
BEGIN
    FOREACH definition IN ARRAY ARRAY[
        'ALTER TABLE public.exercise_levels ADD CONSTRAINT exercise_levels_sets_check CHECK (sets BETWEEN 1 AND 100)',
        'ALTER TABLE public.exercise_levels ADD CONSTRAINT exercise_levels_reps_check CHECK (reps IS NULL OR reps > 0)',
        'ALTER TABLE public.exercise_levels ADD CONSTRAINT exercise_levels_seconds_per_set_check CHECK (seconds_per_set BETWEEN 1 AND 86400)',
        'ALTER TABLE public.exercise_levels ADD CONSTRAINT exercise_levels_rest_seconds_check CHECK (rest_seconds BETWEEN 1 AND 300)',
        'ALTER TABLE public.exercise_levels ADD CONSTRAINT exercise_levels_estimated_seconds_check CHECK (estimated_seconds BETWEEN 1 AND 86400)'
    ] LOOP
        BEGIN EXECUTE definition;
        EXCEPTION WHEN duplicate_object THEN NULL;
        END;
    END LOOP;
END;
$$;
COMMIT;

-- Lần tập cũ có estimated_seconds_snapshot NULL: giữ nguyên chế độ thủ công.
SELECT table_name, column_name, data_type FROM information_schema.columns
WHERE table_schema = 'public' AND (table_name = 'exercise_levels'
    OR (table_name = 'workout_details' AND column_name IN ('estimated_seconds_snapshot', 'automatic_rest_phase')))
ORDER BY table_name, ordinal_position;
