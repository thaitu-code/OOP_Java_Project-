package vn.id.fitnessai.service;

import jakarta.persistence.EntityManagerFactory;
import org.junit.jupiter.api.*;
import org.springframework.context.annotation.*;
import org.springframework.data.jpa.repository.config.EnableJpaRepositories;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.orm.jpa.*;
import org.springframework.orm.jpa.vendor.HibernateJpaVendorAdapter;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;
import vn.id.fitnessai.initializer.DefaultBadgeInitializer;
import vn.id.fitnessai.repository.BadgeRepository;

import javax.sql.DataSource;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

/** Reproduces the legacy NOT NULL metric_type column on disposable H2, without application.properties. */
class BadgeSchemaCompatibilityTest {
    @Configuration
    @EnableTransactionManagement
    @EnableJpaRepositories(basePackages="vn.id.fitnessai.repository")
    @Import({BadgeService.class, DefaultBadgeInitializer.class})
    static class Config {
        @Bean DataSource dataSource() {
            var source=new DriverManagerDataSource("jdbc:h2:mem:legacy_badges;MODE=PostgreSQL;DB_CLOSE_DELAY=-1","sa","");
            new JdbcTemplate(source).execute("""
                CREATE TABLE badges (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(100) NOT NULL UNIQUE,
                    description VARCHAR(500) NOT NULL,
                    icon VARCHAR(500),
                    metric_type VARCHAR(40) NOT NULL CHECK (metric_type IN (
                        'STREAK_DAYS','TOTAL_WORKOUTS','TOTAL_CALORIES_BURNED','MAX_WEIGHT_LIFTED','TOTAL_MEAL_LOGS')),
                    threshold_value BIGINT NOT NULL,
                    active BOOLEAN NOT NULL,
                    created_at TIMESTAMP NOT NULL
                )
                """);
            return source;
        }
        @Bean LocalContainerEntityManagerFactoryBean entityManagerFactory(DataSource source) {
            var factory=new LocalContainerEntityManagerFactoryBean();factory.setDataSource(source);
            factory.setPackagesToScan("vn.id.fitnessai.entity");factory.setJpaVendorAdapter(new HibernateJpaVendorAdapter());
            factory.setJpaPropertyMap(Map.of("hibernate.hbm2ddl.auto","update","hibernate.hbm2ddl.halt_on_error",true,
                    "hibernate.physical_naming_strategy","org.hibernate.boot.model.naming.CamelCaseToUnderscoresNamingStrategy"));
            return factory;
        }
        @Bean PlatformTransactionManager transactionManager(EntityManagerFactory factory) { return new JpaTransactionManager(factory); }
    }

    private static AnnotationConfigApplicationContext app;
    @BeforeAll static void start() { app=new AnnotationConfigApplicationContext(Config.class); }
    @AfterAll static void stop() { if(app!=null)app.close(); }
    @BeforeEach void clearBadges() { app.getBean(BadgeRepository.class).deleteAll(); }

    @Test void defaultInitializerWorksAgainstLegacyRequiredColumnAndIsRepeatable() {
        var initializer=app.getBean(DefaultBadgeInitializer.class);var repository=app.getBean(BadgeRepository.class);
        initializer.run();assertEquals(6,repository.count());
        var before=repository.findAll().stream().map(b->b.getId()).sorted().toList();
        assertTrue(repository.findAll().stream().allMatch(b->"STREAK_DAYS".equals(b.getMetricType())));
        initializer.run();assertEquals(before,repository.findAll().stream().map(b->b.getId()).sorted().toList());
    }

    @Test void administratorCanCreateStreakBadgesWithoutAnExtraMetricInput() {
        var badge=app.getBean(BadgeService.class).createBadge("Custom streak","Check-in 9 ngày","★",9,true);
        var saved=app.getBean(BadgeRepository.class).findById(badge.getId()).orElseThrow();
        assertEquals("STREAK_DAYS",saved.getMetricType());assertEquals(9,saved.getThresholdValue());
    }

    @Test void loadingAndSavingOldBadgesPreservesTheirStoredMetricMetadata() {
        var jdbc=new JdbcTemplate(app.getBean(DataSource.class));
        jdbc.update("INSERT INTO badges(name,description,icon,metric_type,threshold_value,active,created_at) VALUES (?,?,?,?,?,?,CURRENT_TIMESTAMP)",
                "Legacy badge","Existing metadata","★","TOTAL_WORKOUTS",10,false);
        var badge=app.getBean(BadgeRepository.class).findAll().get(0);
        assertEquals("TOTAL_WORKOUTS",badge.getMetricType());
        app.getBean(BadgeService.class).setActive(badge.getId(),false);
        assertEquals("TOTAL_WORKOUTS",jdbc.queryForObject("SELECT metric_type FROM badges WHERE id=?",String.class,badge.getId()));
    }
}
